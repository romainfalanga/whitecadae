// Build only the seven multi-track combinations that the progression permits.
// Usage: node scripts/build-continuous-audio.mjs /path/to/ffmpeg /path/to/scratch
import {execFileSync} from 'node:child_process';
import {mkdirSync,readFileSync,writeFileSync,appendFileSync,statSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {RELEASES} from '../src/music-catalogue.js';
const binary=process.argv[2],scratch=resolve(process.argv[3]||'../audio-build');
if(!binary)throw new Error('Supply an FFmpeg executable.');
const root=fileURLToPath(new URL('../',import.meta.url));
mkdirSync(scratch,{recursive:true});
const run=args=>execFileSync(binary,['-hide_banner','-loglevel','error','-nostdin','-y',...args],{stdio:'inherit'});
const rate=44100, frameBytes=4, catalogue={};
for(const album of RELEASES){
  const decoded=new Map();
  for(const track of album.tracks){
    const pcm=resolve(scratch,track.slug+'.s16');
    run(['-i',resolve(root,'public'+track.src),'-vn','-map_metadata','-1','-ac','2','-ar',String(rate),'-f','s16le',pcm]);
    decoded.set(track.slug,{path:pcm,samples:statSync(pcm).size/frameBytes});
  }
  const variants=[];
  for(const level of [...new Set(album.tracks.map(t=>t.minLevel))].sort((a,b)=>a-b)){
    const tracks=album.tracks.filter(t=>t.minLevel<=level);if(tracks.length<2)continue;
    const raw=resolve(scratch,album.id+'-'+level+'.s16');writeFileSync(raw,'');
    let samples=0;const chapters=[];
    for(const track of tracks){const pcm=decoded.get(track.slug);chapters.push({slug:track.slug,start:samples/rate,duration:pcm.samples/rate});appendFileSync(raw,readFileSync(pcm.path));samples+=pcm.samples;}
    const src='/music/'+album.id+'/continuous-v1-'+level+'.m4a',output=resolve(root,'public'+src);
    run(['-f','s16le','-ar',String(rate),'-ac','2','-i',raw,'-c:a','aac','-b:a','192k','-movflags','+faststart','-map_metadata','-1',output]);
    const bytes=statSync(output).size;if(bytes>25*1024*1024)throw new Error('Worker asset exceeds 25 MiB: '+src);
    variants.push({src,minLevel:level,bytes,duration:samples/rate,chapters});
    console.log(album.album,'level',level,tracks.length+' tracks',bytes+' bytes');
  }
  catalogue[album.id]=variants;
}
writeFileSync(resolve(root,'src/music-continuous.js'),'// Generated by scripts/build-continuous-audio.mjs; contains no puzzle answers.\nexport const CONTINUOUS = '+JSON.stringify(catalogue,null,2)+';\n');
