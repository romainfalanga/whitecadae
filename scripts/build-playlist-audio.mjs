// Normalize each song once; playlists concatenate these complete MPEG streams.
// Usage: node scripts/build-playlist-audio.mjs /path/to/ffmpeg
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {RELEASES} from '../src/music-catalogue.js';

export const AUDIO_VERSION='mp3-cbr192-44100-v1';
const root=fileURLToPath(new URL('../',import.meta.url));

// No ID3, Xing or Info header may describe only the first song of a playlist.
// All frame boundaries and their exact durations are checked before publishing.
export function inspectMp3(bytes){
  let offset=0,frames=0;
  while(offset<bytes.length){
    if(offset+4>bytes.length)throw Error('Incomplete MP3 header.');
    const [a,b,c,d]=bytes.subarray(offset,offset+4);
    if(a!==255||(b&224)!==224||((b>>3)&3)!==3||((b>>1)&3)!==1||c>>4!==11||((c>>2)&3)!==0||d>>6===3)throw Error('Expected stereo MPEG-1 Layer III at 44.1 kHz / 192 kb/s.');
    const size=Math.floor(144000*192/44100)+((c>>1)&1);
    if(offset+size>bytes.length)throw Error('Incomplete MP3 frame.');
    if(!frames){
      const side=offset+4+((b&1)?0:2),tag=side+32;
      if(((bytes[side]<<1)|(bytes[side+1]>>7))!==0)throw Error('The first frame depends on a previous stream.');
      const label=String.fromCharCode(...bytes.subarray(tag,tag+4));
      if(label==='Xing'||label==='Info')throw Error('Per-song duration header must be disabled.');
    }
    frames++;offset+=size;
  }
  if(!frames)throw Error('Empty MP3.');
  return {bytes:bytes.length,frames,duration:frames*1152/44100,sha256:createHash('sha256').update(bytes).digest('hex')};
}

export function buildPlaylistAudio(binary){
  if(!binary)throw Error('Supply an FFmpeg executable.');
  const output=resolve(root,'public/music/playlist');mkdirSync(output,{recursive:true});
  const sources={};
  for(const track of RELEASES.flatMap(album=>album.tracks)){
    const src='/music/playlist/'+track.slug+'.mp3',path=resolve(root,'public'+src);
    execFileSync(binary,['-hide_banner','-loglevel','error','-nostdin','-y','-i',resolve(root,'public'+track.src),'-vn','-map','0:a:0','-map_metadata','-1','-ar','44100','-ac','2','-c:a','libmp3lame','-b:a','192k','-write_xing','0','-id3v2_version','0','-write_id3v1','0',path],{stdio:'inherit'});
    sources[track.slug]={src,...inspectMp3(readFileSync(path))};
    if(sources[track.slug].bytes>25*1024*1024)throw Error('Worker asset exceeds 25 MiB: '+src);
    console.log(track.slug,sources[track.slug].bytes+' bytes',sources[track.slug].duration+' seconds');
  }
  const code='// Generated by scripts/build-playlist-audio.mjs; server-only byte layout.\nexport const PLAYLIST_AUDIO_VERSION = '+JSON.stringify(AUDIO_VERSION)+';\nexport const sourcesBySlug = Object.freeze('+JSON.stringify(sources,null,2)+');\n';
  writeFileSync(resolve(root,'src/playlist-audio-manifest.js'),code);
  return sources;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))buildPlaylistAudio(process.argv[2]);
