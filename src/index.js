function checkWriteOrigin(request,url){
  if(['GET','HEAD','OPTIONS'].includes(request.method))return null;
  const origin=request.headers.get('Origin'),site=request.headers.get('Sec-Fetch-Site');
  if((origin&&origin!==url.origin)||site==='cross-site')return json({error:'Origine de requête non autorisée.'},403);
  if(request.body&&/^\/api\/(signes|echelon|57\/guess|register|login|logout|account|admin|mechanisms|life-tree|ace-circles|private|playlists|loge)(?:\/|$)/.test(url.pathname)&&!/^application\/json(?:\s*;|$)/i.test(request.headers.get('Content-Type')||''))return json({error:'Une requête JSON est requise.'},415);
  return null;
}

async function handleApi(request, env, url) {
  const path = url.pathname.replace(/\/+$/, '') || '/api';
  const method = request.method;
  const route = (m, pattern) => {
    if (m !== method) return null;
    const re = new RegExp('^' + pattern.replace(/:(\w+)/g, '([^/]+)') + '$');
    const match = path.match(re);
    return match ? match.slice(1).map(decodeURIComponent) : null;
  };

  let p;
  if(path==='/api/loge'||path.startsWith('/api/loge/'))return handleLoge(request,env,url,{getUser,json});
  if(path==='/api/playlists/audio')return handlePlaylistAudio(request,env,url,{getUser,json});
  if(path==='/api/playlists'||path.startsWith('/api/playlists/'))return handlePlaylists(request,env,url,{getUser,json});
  if(/^\/api\/(game-master-orange|game-master-blanc|as|mechanisms|life-tree|ace-circles|private)(?:\/|$)/.test(path))return handlePrivate(request,env,url,{getUser,json});
  if(path==='/api/roadmap'||path.startsWith('/api/roadmap/'))return handleRoadmap(request,env,url,{getUser,json});
  if(path==='/api/signes'||path.startsWith('/api/signes/'))return handleEchelon(request,env,path.replace(/^\/api\/signes/,'/api/echelon'),{getUser,json});

  // Retired spaces remain stored, but no client can read, write or join them.
  if (/^\/api\/(conversation|community|videographies|videographie|vg-media|vg-comments|arbres|branches|vocal|voix)(?:\/|$)/.test(path)) {
    return json({error:'Cet espace a été retiré. Le parcours se poursuit dans les musiques et les échelons.'},410);
  }

  if (route('GET', '/api/orange')) {
    const user = await getUser(request, env);
    return json(buildOrange(await gameRows(env, user?.id), user));
  }

  if (/^\/api\/(carre|societes|brainstorms|114)(?:\/|$)/.test(path)) {
    return json({error:'Cet espace a été supprimé.'}, 410);
  }

  if (path === '/api/echelon' || path.startsWith('/api/echelon/') ||
      path === '/api/57' || path === '/api/57/guess') {
    return handleEchelon(request, env, path, { getUser, json });
  }

  // Lyrics are read-only; individual song access is checked below.
  if (['POST', 'PUT', 'PATCH'].includes(request.method) &&
      /^\/api\/(annotations|references|passage-references|connections|essays)(?:\/|$)/.test(path)) {
    return json({ error: 'Les paroles sont désormais en lecture seule.' }, 410);
  }
  if (route('GET', '/api/albums')) return listAlbums(env, request);
  if (route('GET', '/api/music')) return json({albums:musicAlbums(await listeningAccess(request,env))});
  if (path==='/api/aa'||path==='/api/journey') return json({error:'Cette page a été retirée.'},410);
  if ((p = route('GET', '/api/songs/:slug'))) return getSong(env, request, p[0]);

  // --- auth
  if (route('POST', '/api/register')) return register(request, env);
  if (route('POST', '/api/login')) return login(request, env);
  if (route('POST', '/api/logout')) return logout(request, env);
  if (route('GET', '/api/me')) return me(request, env);

  // Member photos use the same visibility checks as the roadmap.
  if (route('GET', '/api/users/:username/avatar')) return json({error:'Cette adresse a été retirée.'},410);

  // Profiles have been retired; existing accounts keep their game progress.
  if (/^\/api\/users\/[^/]+$/.test(path)) return json({error:'La page profil a été retirée.'},410);

  // The retired reset must not erase historical access rights.
  if (route('DELETE', '/api/57/progress')) return json({ error: 'Cette ancienne fonction a été retirée.' }, 410);

  // --- le compte : toujours accessible, sinon on ne pourrait plus en sortir
  if (route('PUT', '/api/account/username')) return updateUsername(request, env);
  if (route('PUT', '/api/account/password')) return updatePassword(request, env);
  if (route('POST', '/api/account/avatar')) return updateAvatar(request, env);

  // --- les pièces hautes : chacune exige son échelon, vérifié dans son
  //     gestionnaire (le corps de la requête et l'échelon du visiteur s'y
  //     lisent ensemble). L'ordre n'a pas d'importance : rien ici n'est
  //     couvert par le barrage plus bas.
  // --- le tronc commun : les interprétations. Ouvert dès l'échelon 1, donc à
  //     tout le monde, visiteur compris : le barrage ne ferme plus que ce qui
  //     est au-dessus. On le garde en place : si un jour un échelon doit se
  //     refermer, il suffit de relever la constante.
  if (path.startsWith('/api/') && !path.startsWith('/api/admin/')) {
    const refus = await requireAccess(request, env, 'interpretations');
    if (refus) return refus;
  }

  // Legacy corpus reader remains available for private historical references.
  if (route('GET', '/api/corpus')) return getCorpus(env, request);

  // --- contributions (connecté)
  if ((p = route('DELETE', '/api/annotations/:id'))) return deleteAnnotation(request, env, +p[0]);
  if ((p = route('DELETE', '/api/references/:id'))) return deleteReference(request, env, +p[0]);
  if ((p = route('DELETE', '/api/passage-references/:id'))) return deletePassageReference(request, env, +p[0]);
  if ((p = route('DELETE', '/api/connections/:id'))) return deleteConnection(request, env, +p[0]);
  if ((p = route('DELETE', '/api/essays/:id'))) return deleteEssay(request, env, +p[0]);

  // --- administration
  if (route('POST', '/api/admin/albums')) return adminCreateAlbum(request, env);
  if ((p = route('PUT', '/api/admin/albums/:id'))) return adminUpdateAlbum(request, env, +p[0]);
  if ((p = route('DELETE', '/api/admin/albums/:id'))) return adminDeleteAlbum(request, env, +p[0]);
  if (route('POST', '/api/admin/songs')) return adminCreateSong(request, env);
  if ((p = route('PUT', '/api/admin/songs/:id'))) return adminUpdateSong(request, env, +p[0]);
  if ((p = route('DELETE', '/api/admin/songs/:id'))) return adminDeleteSong(request, env, +p[0]);
  if ((p = route('PUT', '/api/admin/songs/:id/lyrics'))) return adminSetLyrics(request, env, +p[0]);
  if ((p = route('PUT', '/api/admin/songs/:id/duration'))) return adminSetDuration(request, env, +p[0]);

  return json({ error: 'Route introuvable.' }, 404);
}

